import type { CSSProperties } from "react";

const WIDTHS = [480, 768, 1200, 1536];

type PhotoProps = {
  /** WebP sources use generated variants; other formats are loaded directly. */
  src: string;
  alt: string;
  width: number;
  height: number;
  /** Layout hint for the browser's srcset picker. */
  sizes?: string;
  /** Set on the LCP image only: loads eagerly at high priority. */
  priority?: boolean;
  className?: string;
  style?: CSSProperties;
};

/**
 * Static-export friendly responsive image.
 *
 * `output: "export"` disables the Next.js image optimizer, so the variants are
 * pre-generated by `scripts/images.mjs` and offered here as a plain `srcset`.
 * Width and height are always emitted so the browser can reserve space and the
 * page does not shift as photos arrive.
 */
export default function Photo({
  src,
  alt,
  width,
  height,
  sizes = "100vw",
  priority = false,
  className,
  style,
}: PhotoProps) {
  const hasResponsiveVariants = /\.webp$/i.test(src);
  const base = src.replace(/\.[^.]+$/, "");
  const srcSet = hasResponsiveVariants
    ? WIDTHS.map((w) => `${base}-${w}.webp ${w}w`).join(", ")
    : undefined;

  return (
    <img
      src={hasResponsiveVariants ? `${base}-1200.webp` : src}
      srcSet={srcSet}
      sizes={srcSet ? sizes : undefined}
      alt={alt}
      width={width}
      height={height}
      loading={priority ? "eager" : "lazy"}
      decoding={priority ? "sync" : "async"}
      fetchPriority={priority ? "high" : "auto"}
      className={className}
      style={style}
    />
  );
}
